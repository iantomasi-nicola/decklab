export const guideLocales = { it, en }

let done = false
/** Idempotente. Se i18next non è ancora inizializzato, registra a inizializzazione avvenuta. */
export function registerGuideLocales() {
  if (done) return
  done = true
  const add = () => {
    i18n.addResourceBundle('it', 'translation', it, true, true)
    i18n.addResourceBundle('en', 'translation', en, true, true)
  }
  if (i18n.isInitialized) add()
  else i18n.on('initialized', add)
}
registerGuideLocales()
