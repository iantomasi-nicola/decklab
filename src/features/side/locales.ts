export const sideLocales = { it, en }

let done = false
/** Idempotente. Se i18next non è ancora inizializzato, registra a inizializzazione avvenuta. */
export function registerSideLocales() {
  if (done) return
  done = true
  const add = () => {
    i18n.addResourceBundle('it', 'translation', { side: it }, true, true)
    i18n.addResourceBundle('en', 'translation', { side: en }, true, true)
  }
  if (i18n.isInitialized) add()
  else i18n.on('initialized', add)
}
registerSideLocales()
