type RawKey = keyof typeof it
export type EngKey = RawKey extends infer K ? (K extends `${infer B}_${'one' | 'other'}` ? B : K) : never
export const ENGINE_STRINGS: Record<'it' | 'en', Record<RawKey, string>> = { it, en }
export type EngVars = Record<string, string | number>

export function engText(lang: 'it' | 'en', key: EngKey, vars?: EngVars): string {
  const dict = ENGINE_STRINGS[lang]
  const n = vars?.n
  const plural = (typeof n === 'number' ? `${key}_${n === 1 ? 'one' : 'other'}` : undefined) as RawKey | undefined
  const raw = (plural && plural in dict ? dict[plural] : undefined) ?? dict[key as RawKey] ?? key
  return vars ? raw.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? '')) : raw
}

export type EngT = (key: EngKey | `race.${number}` | `attr.${number}`, vars?: EngVars) => string

/** Hook: `t(chiave, vars)` nella lingua corrente dell'app. */
export function useEngT() {
  const { i18n } = useTranslation()
  const lang: 'it' | 'en' = i18n.resolvedLanguage === 'it' ? 'it' : 'en'
  const t: EngT = (key, vars) => engText(lang, key as EngKey, vars)
  return { lang, t }
}
